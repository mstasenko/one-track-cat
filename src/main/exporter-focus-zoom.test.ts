import { buildFilterGraph } from './exporter'

function request(overrides: Partial<FocusZoomEffect> = {}, canvas: ExportRequest['canvas'] = { width: 320, height: 180, fps: 30, fit: 'contain' }): ExportRequest {
  return {
    canvas,
    sources: [{
      id: 'source',
      metadata: {
        path: '/input.mp4', name: 'input.mp4', size: 1, modifiedAt: 1, duration: 2,
        width: canvas.width, height: canvas.height, fps: canvas.fps, videoCodec: 'h264', hasAudio: false
      }
    }],
    segments: [{ id: 'segment', sourceId: 'source', sourceStart: 0, sourceEnd: 2 }],
    overlays: [],
    outputPath: '/output.mp4',
    focusZooms: [{
      id: 'zoom', start: 0, duration: 2, zoom: 2, focusX: 0.5, focusY: 0.5,
      ...overrides
    }]
  }
}

interface ZoompanExpressions {
  zoom: string
  x: string
  y: string
}

function zoompanExpressions(graph: string): ZoompanExpressions {
  const match = /zoompan=z='([^']+)':x='([^']+)':y='([^']+)'/.exec(graph)
  const zoom = match?.[1]
  const x = match?.[2]
  const y = match?.[3]
  if (!zoom || !x || !y) throw new Error('zoompan expressions are missing from the export graph')
  return { zoom, x, y }
}

/** Test only: evaluate expressions generated by our filter builder, never external input. */
function evaluateExpression(source: string, variables: Readonly<Record<string, number>>): number {
  const value: unknown = new Script(source.replace(/\bif\(/gu, 'choose(')).runInNewContext({
    ...variables, min: Math.min, max: Math.max,
    between: (value: number, start: number, end: number) => Number(value >= start && value <= end),
    choose: (condition: number, yes: number, no: number) => condition ? yes : no
  }, { timeout: 100 })
  if (typeof value !== 'number' || !Number.isFinite(value)) throw new Error('Non-finite zoom expression')
  return value
}

function expectPreviewAndExportToMatch(effect: FocusZoomEffect, canvas: ExportRequest['canvas'], times: number[]): void {
  const expressions = zoompanExpressions(buildFilterGraph(request(effect, canvas), []).graph)
  for (const time of times) {
    const variables = { on: time * canvas.fps, iw: canvas.width, ih: canvas.height }
    const preview = focusCropAtTime(effect, time)
    const zoom = evaluateExpression(expressions.zoom, variables)
    const x = evaluateExpression(expressions.x, { ...variables, zoom })
    const y = evaluateExpression(expressions.y, { ...variables, zoom })
    expect(Number.isFinite(zoom)).toBe(true)
    expect(Number.isFinite(x)).toBe(true)
    expect(Number.isFinite(y)).toBe(true)
    expect(zoom).toBeCloseTo(preview.zoom, 9)
    expect(x).toBeCloseTo(preview.left * canvas.width, 9)
    expect(y).toBeCloseTo(preview.top * canvas.height, 9)
  }
}

describe('focus zoom export filter', () => {
  it('keeps default/frame zooms in zoompan and emits circles as a small transparent ring overlay', () => {
    const canvas = { width: 320, height: 180, fps: 30, fit: 'contain' as const }
    const frame = buildFilterGraph(request({}, canvas), [])
    const explicitFrame = buildFilterGraph(request({ mode: 'frame' }, canvas), [])
    const circle = buildFilterGraph(request({ mode: 'circle', start: 0.2, duration: 1, focusX: 0, focusY: 1 }, canvas), [])

    expect(frame.graph).toContain('zoompan=')
    expect(explicitFrame.graph).toContain('zoompan=')
    expect(circle.graph).not.toContain('zoompan=')
    expect(circle.videoLabel).toBe('focusCircle0')
    expect(circle.graph).toContain('color=c=black@0.0:s=79x79:r=30:d=1.000000,setpts=PTS+0.200000/TB')
    expect(circle.graph).not.toContain('crop=40:40:0:140')
    expect(circle.graph).not.toContain('scale=79:79:flags=lanczos')
    expect(circle.graph).toContain("format=rgba,geq=r='")
    expect(circle.graph).toContain('atan2')
    expect(circle.graph).toContain('(T-0.200000)/0.500000')
    expect(circle.graph).toContain(":enable='between(t\\,0.200000\\,1.200000)'")
    expect(circle.graph).toContain('eof_action=pass:repeatlast=1')
    expect(circle.graph).toContain(':format=rgb:enable=')
    const smaller = buildFilterGraph(request({ mode: 'circle', zoom: 4 }, canvas), [])
    expect(smaller.graph).toContain('color=c=black@0.0:s=40x40:')
    expect(smaller.graph).not.toContain('zoompan=')
  })

  it('uses shared preview/export ramps across ramp-in, hold, ramp-out, and the exact end', () => {
    const canvas = { width: 320, height: 180, fps: 29.97, fit: 'contain' as const }
    const defaultEffect: FocusZoomEffect = { id: 'default', start: 0.125, duration: 1.75, zoom: 4, focusX: 0.2, focusY: 0.8 }
    const minimumEffect: FocusZoomEffect = { id: 'minimum', start: 0.125, duration: 1.75, transitionDuration: 0.01, zoom: 4, focusX: 0.2, focusY: 0.8 }
    const maximumEffect: FocusZoomEffect = { id: 'maximum', start: 0.125, duration: 1.75, transitionDuration: 10, zoom: 4, focusX: 0.2, focusY: 0.8 }
    const shortEffect: FocusZoomEffect = { id: 'short', start: 0.125, duration: 0.08, transitionDuration: 10, zoom: 4, focusX: 0.2, focusY: 0.8 }
    const effects = [defaultEffect, minimumEffect, maximumEffect, shortEffect]

    expect(focusZoomDefaultTransitionDuration).toBe(0.5)
    expect(focusZoomMinTransitionDuration).toBe(0.05)
    expect(focusZoomMaxTransitionDuration).toBe(5)
    expect(focusZoomTransitionDuration(defaultEffect)).toBe(0.5)
    expect(focusZoomTransitionDuration(minimumEffect)).toBe(0.05)
    expect(focusZoomTransitionDuration(maximumEffect)).toBe(0.875)
    expect(focusZoomTransitionDuration(shortEffect)).toBe(0.04)

    for (const effect of effects) {
      const ramp = focusZoomTransitionDuration(effect)
      expectPreviewAndExportToMatch(effect, canvas, [
        effect.start,
        effect.start + ramp / 2,
        effect.start + ramp,
        effect.start + effect.duration / 2,
        effect.start + effect.duration - ramp,
        effect.start + effect.duration - ramp / 2,
        effect.start + effect.duration
      ])
    }
  })
})
